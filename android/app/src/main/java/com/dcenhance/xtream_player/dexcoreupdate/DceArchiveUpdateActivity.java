  @SuppressLint("ClickableViewAccessibility")
  private void tactile(TextView view) {
    view.setFocusable(true); view.setClickable(true);
    view.setOnTouchListener((target, event) -> {
      if (!target.isEnabled()) return false;
      boolean pressed = event.getActionMasked() == android.view.MotionEvent.ACTION_DOWN;
      target.animate().scaleX(pressed ? .98f : 1f).scaleY(pressed ? .98f : 1f).setDuration(120).start();
      return false;
    });
  }
  private int contrastOnAccent() { double luminance = luminance(accent); return luminance > .56d ? Color.rgb(12, 14, 18) : Color.WHITE; }
  private TextView text(String value, int sp, int color, boolean bold) { TextView view = new TextView(this); view.setText(value); view.setTextSize(sp); view.setTextColor(color); view.setGravity(Gravity.START); view.setTextDirection(View.TEXT_DIRECTION_LOCALE); if (bold) view.setTypeface(Typeface.DEFAULT_BOLD); return view; }
  private GradientDrawable round(int color, int radius) { GradientDrawable shape = new GradientDrawable(); shape.setColor(color); shape.setCornerRadius(dp(radius)); return shape; }
  // The card carries a hairline of the host's own brand so it reads as one of the
