  // 0 = primary host text colour, 1 = secondary.
  private int hostThemeText(int index) {
    int attribute = index == 0 ? android.R.attr.textColorPrimary : android.R.attr.textColorSecondary;
    for (int themeResource : hostThemeResources()) {
      if (themeResource == 0) continue;
      android.content.res.Resources.Theme hostTheme = getResources().newTheme();
      try {
        hostTheme.applyStyle(themeResource, true);
      } catch (Exception ignored) { continue; }
      int color = resolveThemeColor(hostTheme, attribute);
      // A themed *text* colour decides how the whole notice reads. Hosts keep warning
      // and brand hues in the same attributes, and a hued one walks toward white on the
      // card - which is exactly how the notice text turned pink inside a red-branded
      // app. Only a near-neutral tone is accepted as text; a hued one falls through to
      // the app's own detected text colours.
      if (Color.alpha(color) >= 128 && isNeutralTone(color)) return color;
    }
    return index == 0 ? DETECTED_TEXT : DETECTED_MUTED;
  }

  private static boolean isNeutralTone(int color) {
    int high = Math.max(Color.red(color), Math.max(Color.green(color), Color.blue(color)));
    int low = Math.min(Color.red(color), Math.min(Color.green(color), Color.blue(color)));
    return high - low <= 40;
  }

  private int resolveHostBackground() {
    int frameworkDefault = 0;
    for (int themeResource : hostThemeResources()) {
      if (themeResource == 0) continue;
      android.content.res.Resources.Theme hostTheme = getResources().newTheme();
      try {
        hostTheme.applyStyle(themeResource, true);
      } catch (Exception ignored) { continue; }
      int background = resolveThemeColor(hostTheme, android.R.attr.windowBackground);
      if (Color.alpha(background) < 128) background = resolveThemeColor(hostTheme, android.R.attr.colorBackground);
      if (Color.alpha(background) < 128) continue;
      if (!isBaselineBackground(background)) return background;
      if (frameworkDefault == 0) frameworkDefault = background;
    }
    // The app's own palette beats a framework default its theme never replaced: a
    // Compose/Flutter host keeps its colours in code, so its theme still resolves
    // to the platform grey even though the app renders near-black or white.
    if (Color.alpha(DETECTED_BACKGROUND) >= 128) return DETECTED_BACKGROUND;
    return frameworkDefault != 0 ? frameworkDefault : DETECTED_BACKGROUND;
  }

  private static boolean isBaselineBackground(int color) {
    for (int baseline : BASELINE_BACKGROUNDS) if (color == baseline) return true;
    return false;
  }

  private int resolveHostPrimaryColor() {
    int declaredPrimary = getResources().getIdentifier("colorPrimary", "attr", getPackageName());
    for (int themeResource : hostThemeResources()) {
      if (themeResource == 0) continue;
      android.content.res.Resources.Theme hostTheme = getResources().newTheme();
      try {
        hostTheme.applyStyle(themeResource, true);
      } catch (Exception ignored) { continue; }
      // The framework attribute is the app's own declaration; the package-scoped
      // identifier only matters on hosts that redefine the attribute themselves.
      int primary = resolveThemeColor(hostTheme, android.R.attr.colorPrimary);
      if (!isUsableThemePrimary(hostTheme, primary)) primary = resolveThemeColor(hostTheme, declaredPrimary);
      if (isUsableThemePrimary(hostTheme, primary)) return primary;
    }
    // A host whose colours live in code (Compose, Flutter) exposes no themed primary,
    // so the primary detected in its own sources is authoritative, not a generic hue.
    if (Color.alpha(DETECTED_PRIMARY) >= 128) return DETECTED_PRIMARY;
    for (int themeResource : hostThemeResources()) {
      if (themeResource == 0) continue;
      android.content.res.Resources.Theme hostTheme = getResources().newTheme();
      try {
        hostTheme.applyStyle(themeResource, true);
      } catch (Exception ignored) { continue; }
      int accent = resolveThemeColor(hostTheme, android.R.attr.colorAccent);
      if (isUsableThemePrimary(hostTheme, accent)) return accent;
    }
    return DETECTED_PRIMARY;
  }

  /** The launcher activity theme first, then the application theme. */
  private int[] hostThemeResources() {
    int launcherTheme = 0;
    int applicationTheme = 0;
    try {
      Intent launcher = getPackageManager().getLaunchIntentForPackage(getPackageName());
      if (launcher != null && launcher.getComponent() != null) {
        launcherTheme = getPackageManager().getActivityInfo(launcher.getComponent(), 0).getThemeResource();
      }
    } catch (Exception ignored) { /* Falls back to the application theme. */ }
    try {
      applicationTheme = getApplicationInfo().theme;
    } catch (Exception ignored) { /* Falls back to the detected primary. */ }
    return new int[]{launcherTheme, applicationTheme};
  }

  @SuppressWarnings("deprecation")
  private int resolveThemeColor(android.content.res.Resources.Theme hostTheme, int attribute) {
    if (attribute == 0) return Color.TRANSPARENT;
    TypedValue value = new TypedValue();
    if (!hostTheme.resolveAttribute(attribute, value, true)) return Color.TRANSPARENT;
    if (value.type >= TypedValue.TYPE_FIRST_COLOR_INT && value.type <= TypedValue.TYPE_LAST_COLOR_INT) return value.data;
    if (value.resourceId != 0) {
      try { return getResources().getColor(value.resourceId); } catch (Exception ignored) { return Color.TRANSPARENT; }
    }
    return Color.TRANSPARENT;
  }

  private boolean isUsableThemePrimary(android.content.res.Resources.Theme hostTheme, int color) {
    if (Color.alpha(color) < 128) return false;
    // A theme that never declared a brand primary inherits one of these baseline
    // hues; treating them as the app's identity paints the notice in Material
    // purple for every host that keeps its colours in code.
    if (color == 0xFF6200EE || color == 0xFF3F51B5 || color == 0xFF6750A4 || color == 0xFF2196F3) return false;
    int background = resolveThemeColor(hostTheme, android.R.attr.windowBackground);
    if (Color.alpha(background) >= 128) {
      int red = Color.red(color) - Color.red(background);
      int green = Color.green(color) - Color.green(background);
      int blue = Color.blue(color) - Color.blue(background);
      if (red * red + green * green + blue * blue < 24 * 24) return false;
    }
    return true;
  }

  private static double channel(int value) {
    double srgb = value / 255d;
    return srgb <= .03928d ? srgb / 12.92d : Math.pow((srgb + .055d) / 1.055d, 2.4d);
  }

  private static double luminance(int color) {
    return .2126d * channel(Color.red(color)) + .7152d * channel(Color.green(color)) + .0722d * channel(Color.blue(color));
  }

  private static double contrast(int first, int second) {
    double a = luminance(first), b = luminance(second);
    return (Math.max(a, b) + .05d) / (Math.min(a, b) + .05d);
  }

  private static int blend(int from, int to, double amount) {
    return Color.rgb(
        (int) Math.round(Color.red(from) + (Color.red(to) - Color.red(from)) * amount),
        (int) Math.round(Color.green(from) + (Color.green(to) - Color.green(from)) * amount),
        (int) Math.round(Color.blue(from) + (Color.blue(to) - Color.blue(from)) * amount));
  }

  private static boolean isLight(int background) { return luminance(background) > .45d; }

  private static int textOn(int background) { return isLight(background) ? 0xFF14121A : 0xFFF4F2FA; }

  // Keep the host's own hue but walk it toward the readable end until the contrast
  // holds, so a pale brand colour is still legible on a light card and a deep one on
  // a dark card.
  private static int readableOn(int color, int background, double minimum) {
    if (Color.alpha(color) < 128) color = textOn(background);
    if (contrast(color, background) >= minimum) return color;
    int toward = isLight(background) ? Color.BLACK : Color.WHITE;
    for (int step = 1; step <= 12; step++) {
      int adjusted = blend(color, toward, step / 12d);
      if (contrast(adjusted, background) >= minimum) return adjusted;
    }
    return toward;
  }

  private static int readableText(int candidate, int background, int fallback, double minimum) {
    if (Color.alpha(candidate) >= 128 && contrast(candidate, background) >= minimum) return candidate;
    // The platform's own text colour and the host's detected one describe the same
    // role; the one that actually stands out on this card wins, so a light host is
    // never labelled with near-white text that has to be walked back down.
    int computed = textOn(background);
    int base = Color.alpha(fallback) >= 128 && contrast(fallback, background) > contrast(computed, background) ? fallback : computed;
    return readableOn(base, background, minimum);
  }

  // Material tints an elevated surface with the app's own primary; a fixed grey card
  // is exactly what made the notice read as a foreign dialog inside its host.
  private int noticeSurface(int background, int brand) {
    boolean light = isLight(background);
    int card = blend(background, brand, light ? .03d : .05d);
    if (!light) {
      card = blend(card, Color.WHITE, .03d);
      if (contrast(card, background) < 1.06d) card = blend(background, Color.WHITE, .09d);
    }
    return card;
  }

