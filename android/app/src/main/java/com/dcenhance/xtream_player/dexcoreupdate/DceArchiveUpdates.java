  /** Update lane of this installation. A debuggable build is a lab build. */
  private static String updateLane(Context context) {
    try {
      android.content.pm.ApplicationInfo info = context.getApplicationInfo();
      return (info.flags & android.content.pm.ApplicationInfo.FLAG_DEBUGGABLE) != 0 ? "debug" : "release";
    } catch (Exception invalid) { return "release"; }
  }
  /**
   * Lane descriptor beside the configured endpoint: <app>/update.json becomes
   * <app>/<lane>/update.json, so debug and release installs update independently.
   * An internal endpoint already carries its edition-and-lane path and is used as is.
   */
  private static URL laneEndpointUrl(Context context) throws Exception {
    URL endpoint = endpointUrl();
    String path = endpoint.getPath();
    if (path.contains("/updates/")) return endpoint;
    return new URL(endpoint.toString().replace("/update.json", "/" + updateLane(context) + "/update.json"));
  }
  /** Directory the lane descriptor must point its downloads into. */
  private static String laneDirectoryPath(Context context) throws Exception {
    String path = laneEndpointUrl(context).getPath();
    return path.substring(0, path.lastIndexOf('/') + 1);
  }
  private static URL endpointUrl() throws Exception { return new URL(concealed(ENDPOINT_DATA, ENDPOINT_SEED)); }
  private static String concealed(int[] data, int seed) {
    byte[] clear = new byte[data.length]; int state = seed;
    for (int i = 0; i < data.length; i++) { state = state * 1664525 + 1013904223; clear[i] = (byte) (data[i] ^ (state & 0xff)); }
    return new String(clear, java.nio.charset.StandardCharsets.UTF_8);
  }
