  private static UpdatePolicy strictUpdatePolicy(JSONObject policy) throws Exception {
    String mode = requireJsonString(policy, "mode");
    if (!("optional".equals(mode) || "recommended".equals(mode) || "required".equals(mode))) throw new java.io.IOException("Invalid update mode");
    Long minimum = optionalNonNegativeLong(policy, "minimumVersionCode");
    Long expiry = optionalUtcExpiration(policy, "expiresAt");
    return new UpdatePolicy(mode, minimum, expiry);
  }

  static boolean isRequiredUpdate(Context context, JSONObject update) {
    try {
      UpdatePolicy policy = strictUpdatePolicy(requireJsonObject(update, "updatePolicy"));
      if (!"required".equals(policy.mode)) return false;
      if (policy.minimumVersionCode != null && installedVersion(context) >= policy.minimumVersionCode) return false;
      if (policy.expiresAtMillis != null && System.currentTimeMillis() >= policy.expiresAtMillis) return false;
      return true;
    } catch (Exception invalid) { return false; }
  }

