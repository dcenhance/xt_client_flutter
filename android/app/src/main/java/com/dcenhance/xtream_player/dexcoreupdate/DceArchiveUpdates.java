  static DataChangelog dataChangelogFor(JSONObject update, Locale locale) {
    try {
      JSONObject catalog = catalogFor(update);
      Object raw = catalog == null ? null : catalog.opt("changelog");
      if (!(raw instanceof JSONObject)) return null;
      JSONObject block = (JSONObject) raw;
      if (block.toString().length() > MAX_CONTENT_CHANGELOG_JSON_BYTES) return null;
      if (!"content".equals(requireJsonString(block, "kind"))) return null;
      String dataVersion = requireJsonString(block, "dataVersion").trim();
      if (!dataVersion.matches("\\d{4}\\.\\d{2}\\.\\d{2}(\\.\\d{1,3})?")) return null;
      String publishedAt = requireJsonString(block, "publishedAt").trim();
      if (!publishedAt.matches("\\d{4}-\\d{2}-\\d{2}")) return null;
      String revision = requireJsonString(block, "revision").trim();
      if (!revision.matches("[0-9a-f]{8,64}") || !revision.equals(requireJsonString(catalog, "revision"))) return null;
      int fileCount = (int) requirePositiveLong(block, "fileCount");
      long totalSizeBytes = requirePositiveLong(block, "totalSizeBytes");
      if (fileCount != catalog.getJSONArray("files").length()) return null;
      if (totalSizeBytes != requirePositiveLong(catalog, "totalSizeBytes")) return null;
      JSONArray categories = block.getJSONArray("categories");
      if (categories.length() == 0 || categories.length() > MAX_CHANGELOG_CATEGORIES) return null;
      String[] names = new String[categories.length()];
      for (int index = 0; index < names.length; index++) {
        Object value = categories.get(index);
        if (!(value instanceof String) || ((String) value).isEmpty()) return null;
        names[index] = (String) value;
      }
      JSONObject notices = block.getJSONObject("notices");
      if (notices.length() == 0 || notices.length() > MAX_CHANGELOG_TABLES) return null;
      JSONObject notice = null;
      for (String key : changelogLanguageKeys(locale)) {
        Object candidate = notices.opt(key);
        if (candidate instanceof JSONObject) { notice = (JSONObject) candidate; break; }
      }
      if (notice == null) return null;
      String heading = requireBoundedText(notice, "heading", MAX_CHANGELOG_LABEL_CHARS);
      String versionLine = requireBoundedText(notice, "versionLine", MAX_CHANGELOG_LABEL_CHARS);
      String verifiedLine = requireBoundedText(notice, "verifiedLine", MAX_CHANGELOG_LABEL_CHARS);
      JSONObject labels = notice.getJSONObject("labels");
      JSONObject notes = notice.getJSONObject("notes");
      String[] labelValues = new String[names.length];
      String[][] noteValues = new String[names.length][];
      int total = 0;
      for (int index = 0; index < names.length; index++) {
        String category = names[index];
        labelValues[index] = requireBoundedText(labels, category, MAX_CHANGELOG_LABEL_CHARS);
        JSONArray values = notes.getJSONArray(category);
        if (values.length() == 0 || values.length() > MAX_CHANGELOG_ENTRIES) return null;
        String[] entries = new String[values.length()];
        for (int entry = 0; entry < entries.length; entry++) {
          Object value = values.get(entry);
          if (!(value instanceof String)) return null;
          String text = ((String) value).trim();
          if (text.isEmpty() || text.length() > MAX_CHANGELOG_ENTRY_CHARS) return null;
          entries[entry] = text;
        }
        noteValues[index] = entries;
        total += entries.length;
      }
      if (total == 0) return null;
      return new DataChangelog(heading, versionLine, verifiedLine, dataVersion, publishedAt, revision,
                               fileCount, totalSizeBytes, labelValues, noteValues);
    } catch (Exception invalid) { return null; }
  }

  static String catalogRevision(JSONObject update) {
    JSONObject catalog = validCatalog(update);
    if (catalog == null) return null;
    try { return requireJsonString(catalog, "revision"); } catch (Exception invalid) { return null; }
  }

  /** True while the signed content revision differs from the acknowledged one. */
  static boolean catalogUpdateAvailable(Context context, JSONObject update) {
    if (context == null) return false;
    String revision = catalogRevision(update);
    if (revision == null) return false;
    String seen = context.getSharedPreferences(PREFERENCES, Context.MODE_PRIVATE).getString(SEEN_CATALOG_REVISION, null);
    return !revision.equals(seen);
  }

  static boolean isRequiredCatalog(JSONObject update) {
    try {
      JSONObject catalog = validCatalog(update);
      if (catalog == null) return false;
      if (!"required".equals(requireJsonString(catalog, "mode"))) return false;
      Long expiry = optionalUtcExpiration(catalog, "expiresAt");
      return expiry == null || System.currentTimeMillis() < expiry;
    } catch (Exception invalid) { return false; }
  }

  /** Folder that holds one app, e.g. /archive/projects/apks/<slug>/update.json -> /archive/projects/apks/ */
  private static String archiveRootPath(URL endpoint) {
    String path = endpoint.getPath();
    int lastSlash = path.lastIndexOf('/');
    int previous = lastSlash > 0 ? path.lastIndexOf('/', lastSlash - 1) : -1;
    return previous <= 0 ? path : path.substring(0, previous + 1);
  }

  /**
   * Strict validation of the optional content block. Every file URL must live on
   * the archive origin inside this app's own folder, carry a SHA-256 and match
   * the advertised total, so a signed descriptor can never point the client at
   * another app's bytes or an unverifiable payload.
   */
  static JSONObject validCatalog(JSONObject update) {
    if (update == null || !update.has("catalog") || update.isNull("catalog")) return null;
    try {
      JSONObject catalog = requireJsonObject(update, "catalog");
      String revision = requireJsonString(catalog, "revision");
      if (!revision.matches("[0-9a-f]{8,64}")) return null;
      String mode = requireJsonString(catalog, "mode");
      if (!("optional".equals(mode) || "recommended".equals(mode) || "required".equals(mode))) return null;
      long total = requirePositiveLong(catalog, "totalSizeBytes");
      if (total <= 0L || total > MAX_CATALOG_TOTAL_BYTES) return null;
      JSONArray files = catalog.optJSONArray("files");
      if (files == null || files.length() == 0 || files.length() > MAX_CATALOG_FILES) return null;
      URL endpoint = endpointUrl();
      String root = archiveRootPath(endpoint);
      String appPath = endpoint.getPath().substring(root.length(), endpoint.getPath().lastIndexOf('/'));
      if (requirePositiveLong(catalog, "fileCount") != files.length()) return null;
      java.util.HashSet<String> names = new java.util.HashSet<>();
      long summed = 0L;
      for (int index = 0; index < files.length(); index++) {
        JSONObject file = files.optJSONObject(index);
        if (file == null) return null;
        long size = requirePositiveLong(file, "sizeBytes");
        if (size <= 0L || size > MAX_APK_BYTES) return null;
        if (!requireJsonString(file, "sha256").matches("[0-9a-fA-F]{64}")) return null;
        if (requireJsonString(file, "label").length() == 0) return null;
        String name = requireJsonString(file, "file");
        if (name.length() == 0 || name.contains("..") || name.indexOf('/') >= 0 || name.indexOf((char) 92) >= 0 || !names.add(name)) return null;
        URL fileUrl = new URL(requireJsonString(file, "url"));
        if (!sameArchiveOrigin(endpoint, fileUrl)) return null;
        String filePath = fileUrl.getPath();
        if (!filePath.startsWith(root + "data/" + appPath + "/") && !filePath.startsWith(root + appPath + "/")) return null;
        if (!filePath.endsWith("/" + name)) return null;
        summed += size;
      }
      if (summed != total) return null;
      return catalog;
    } catch (Exception invalid) { return null; }
  }

  static boolean catalogContentVerified(Context context, JSONObject update) {
    try {
      JSONObject catalog = validCatalog(update);
      if (catalog == null) return false;
      File directory = contentDirectoryFor(context, catalog);
      JSONArray files = catalog.getJSONArray("files");
      for (int index = 0; index < files.length(); index++) {
        JSONObject file = files.getJSONObject(index);
        File target = new File(directory, requireJsonString(file, "file"));
        if (!target.isFile() || target.length() != requirePositiveLong(file, "sizeBytes")) return false;
        if (!matchesSha256(target, requireJsonString(file, "sha256"))) return false;
      }
      return true;
    } catch (Exception invalid) { return false; }
  }

  /** App-private home of the verified content for the revision in this descriptor. */
  public static File contentDirectory(Context context, JSONObject update) {
    try {
      JSONObject catalog = validCatalog(update);
      if (catalog == null || context == null) return null;
      return contentDirectoryFor(context, catalog);
    } catch (Exception invalid) { return null; }
  }

  private static File contentDirectoryFor(Context context, JSONObject catalog) throws Exception {
    File root = new File(context.getFilesDir(), CONTENT_DIRECTORY);
    return new File(root, requireJsonString(catalog, "revision"));
  }

  /**
   * Records that this install is aware of the current content revision, and tells
   * the host app that verified bytes are on disk. The app stays in charge of what
   * it does with the content; the notice never claims it imported anything.
   */
  public static void acknowledgeCatalog(Context context, JSONObject update) {
    if (context == null) return;
    try {
      String revision = catalogRevision(update);
      if (revision == null) return;
      context.getSharedPreferences(PREFERENCES, Context.MODE_PRIVATE).edit().putString(SEEN_CATALOG_REVISION, revision).apply();
      // Postponement acknowledges a revision but must never publish content-ready.
      File completed = new File(contentDirectory(context, update), "verified-catalog.json");
      if (!completed.isFile()) return;
      Intent ready = new Intent(context.getPackageName() + CONTENT_READY_ACTION).setPackage(context.getPackageName());
      ready.putExtra("revision", revision);
      File directory = contentDirectory(context, update);
      if (directory != null) ready.putExtra("directory", directory.getAbsolutePath());
      context.sendBroadcast(ready);
    } catch (Exception ignored) { }
  }

  static int catalogPostponementsUsed(Context context, String revision) {
    if (context == null || revision == null) return NOT_NOW_LIMIT;
    return context.getSharedPreferences(PREFERENCES, Context.MODE_PRIVATE).getInt(CATALOG_NOT_NOW_PREFIX + revision, 0);
  }

  static boolean canPostponeCatalog(Context context, String revision) {
    return catalogPostponementsUsed(context, revision) < NOT_NOW_LIMIT;
  }

  static void recordCatalogPostponement(Context context, String revision) {
    if (context == null || revision == null) return;
    int used = catalogPostponementsUsed(context, revision);
    if (used >= NOT_NOW_LIMIT) return;
    context.getSharedPreferences(PREFERENCES, Context.MODE_PRIVATE).edit().putInt(CATALOG_NOT_NOW_PREFIX + revision, used + 1).apply();
  }

  /** Result of a verified content transfer; the app decides how to consume it. */
  static final AtomicBoolean CATALOG_ACTIVE = new AtomicBoolean(false);
  private static WeakReference<CatalogResult> CATALOG_RESULT = new WeakReference<>(null);
  public interface CatalogResult {
    void onReady(File directory);
    void onUnavailable(boolean needsArchive);
  }

  public static void downloadCatalog(Activity activity, JSONObject update, DownloadProgress progress, CatalogResult result) {
    JSONObject catalog = catalogFor(update);
    if (activity == null || catalog == null || result == null) {
      if (result != null) result.onUnavailable(false);
      return;
    }
    CATALOG_RESULT = new WeakReference<>(result);
    ACTIVE_PROGRESS = new WeakReference<>(progress);
    if (!CATALOG_ACTIVE.compareAndSet(false, true)) { attachProgress(activity, progress); return; }
    if (!DOWNLOAD_ACTIVE.compareAndSet(false, true)) { CATALOG_ACTIVE.set(false); result.onUnavailable(false); return; }
    final String snapshot = update.toString();
    EXECUTOR.execute(() -> {
      boolean needsArchive = false;
      try {
        File directory = downloadVerifiedContent(activity, new JSONObject(snapshot), catalog, progress);
        if (directory == null) throw new java.io.IOException("content unavailable");
        acknowledgeCatalog(activity, new JSONObject(snapshot));
        CATALOG_ACTIVE.set(false); DOWNLOAD_ACTIVE.set(false);
        MAIN.post(() -> { CatalogResult current = CATALOG_RESULT.get(); if (current != null) current.onReady(directory); });
        return;
      } catch (java.io.IOException gated) {
        // A protected archive answers with a redirect to its gate page. That is not
        // a broken download, so the notice tells the user where to get the bytes.
        needsArchive = "content-gated".equals(gated.getMessage());
      } catch (Exception ignored) { }
      final boolean archiveRequired = needsArchive;
      CATALOG_ACTIVE.set(false); DOWNLOAD_ACTIVE.set(false);
      MAIN.post(() -> { CatalogResult current = CATALOG_RESULT.get(); if (current != null) current.onUnavailable(archiveRequired); });
    });
  }

  private static File downloadVerifiedContent(Activity activity, JSONObject update, JSONObject catalog, DownloadProgress progress) throws Exception {
    JSONArray files = catalog.getJSONArray("files");
    long total = requirePositiveLong(catalog, "totalSizeBytes");
    File directory = contentDirectoryFor(activity, catalog);
    if (!directory.isDirectory() && !directory.mkdirs()) throw new java.io.IOException("Cannot create private content directory");
    long done = 0L;
    reportProgress(activity, progress, 0L, total);
    URL endpoint = endpointUrl();
    for (int index = 0; index < files.length(); index++) {
      JSONObject file = files.getJSONObject(index);
      String name = requireJsonString(file, "file");
      long size = requirePositiveLong(file, "sizeBytes");
      String sha256 = requireJsonString(file, "sha256").toLowerCase(Locale.US);
      File target = new File(directory, name);
      if (matchesSha256(target, sha256) && target.length() == size) {
        done += size;
        reportProgress(activity, progress, done, total);
        continue;
      }
      URL source = new URL(requireJsonString(file, "url"));
      if (!sameArchiveOrigin(endpoint, source)) throw new java.io.IOException("Cross-origin content blocked");
      File temporary = File.createTempFile("content-", ".part", directory);
      try {
        HttpURLConnection connection = (HttpURLConnection) source.openConnection();
        connection.setConnectTimeout(10000); connection.setReadTimeout(60000); connection.setInstanceFollowRedirects(false);
        int status = connection.getResponseCode();
        if (status == 301 || status == 302 || status == 303 || status == 307 || status == 308) throw new java.io.IOException("content-gated");
        if (status == 401 || status == 403) throw new java.io.IOException("content-gated");
        if (status != 200) throw new java.io.IOException("content HTTP " + status);
        long declared = connection.getContentLengthLong();
        if (declared > MAX_APK_BYTES || (declared >= 0L && declared != size)) throw new java.io.IOException("Unexpected content length");
        MessageDigest digest = MessageDigest.getInstance("SHA-256");
        long reportedBytes = 0L;
        long reportedAt = System.currentTimeMillis();
        try (InputStream input = new BufferedInputStream(connection.getInputStream()); FileOutputStream output = new FileOutputStream(temporary)) {
          byte[] buffer = new byte[16384];
          long received = 0L;
          for (int count; (count = input.read(buffer)) != -1;) {
            received += count;
            if (received > size) throw new java.io.IOException("Content exceeds signed size");
            digest.update(buffer, 0, count);
            output.write(buffer, 0, count);
            long overall = done + received;
            if (progress != null && (received >= size || overall - reportedBytes >= PROGRESS_STEP_BYTES || System.currentTimeMillis() - reportedAt >= PROGRESS_INTERVAL_MS)) {
              reportedBytes = overall; reportedAt = System.currentTimeMillis();
              reportProgress(activity, progress, overall, total);
            }
          }
        } finally { connection.disconnect(); }
        if (!sha256.equals(hex(digest.digest())) || temporary.length() != size) throw new java.io.IOException("Content checksum or length mismatch");
        if (target.exists() && !target.delete()) throw new java.io.IOException("Cannot replace stale content");
        if (!temporary.renameTo(target)) throw new java.io.IOException("Cannot promote verified content");
      } finally { if (temporary.exists()) temporary.delete(); }
      done += size;
      reportProgress(activity, progress, done, total);
    }
    reportVerifying(activity, progress);
    // Publish the complete plan atomically, only after every signed byte passed.
    File marker = new File(directory, "verified-catalog.json");
    File stagedMarker = new File(directory, "verified-catalog.json.tmp");
    try (FileOutputStream output = new FileOutputStream(stagedMarker)) {
      output.write(catalog.toString().getBytes(java.nio.charset.StandardCharsets.UTF_8));
      output.getFD().sync();
    }
    if (!stagedMarker.renameTo(marker)) throw new java.io.IOException("Cannot activate verified content");
    return directory;
  }

  private static Long optionalUtcExpiration(JSONObject object, String key) throws Exception {
    if (!object.has(key) || object.isNull(key)) return null;
    String value = requireJsonString(object, key);
    Matcher match = UTC_RFC3339.matcher(value);
    if (!match.matches()) throw new java.io.IOException("Invalid UTC expiry");
    GregorianCalendar calendar = new GregorianCalendar(TimeZone.getTimeZone("UTC"), Locale.US);
    calendar.setLenient(false); calendar.clear();
    int millis = 0;
    if (match.group(7) != null) millis = Integer.parseInt((match.group(7) + "000").substring(0, 3));
    calendar.set(Integer.parseInt(match.group(1)), Integer.parseInt(match.group(2)) - 1, Integer.parseInt(match.group(3)), Integer.parseInt(match.group(4)), Integer.parseInt(match.group(5)), Integer.parseInt(match.group(6)));
    calendar.set(Calendar.MILLISECOND, millis);
    return calendar.getTimeInMillis();
  }

  private static File downloadVerifiedApk(Context context, JSONObject update, DownloadProgress progress) throws Exception {
    String sha256 = requireJsonString(update, "sha256").toLowerCase(Locale.US);
    long version = requirePositiveLong(update, "versionCode");
    long expectedSize = requirePositiveLong(update, "sizeBytes");
    File directory = new File(context.getFilesDir(), "dexcore-archive-updates");
    if (!directory.isDirectory() && !directory.mkdirs()) throw new java.io.IOException("Cannot create private update directory");
    File apk = new File(directory, "update-" + version + ".apk");
    if (matchesSha256(apk, sha256) && apk.length() == expectedSize && validateArchiveIdentity(context, apk, update)) { reportProgress(context, progress, expectedSize, expectedSize); return apk; }
    File temporary = File.createTempFile("update-", ".part", directory);
    try {
      URL endpoint = endpointUrl();
      URL download = new URL(requireJsonString(update, "downloadUrl"));
      if (!sameArchiveOrigin(endpoint, download)) throw new java.io.IOException("Cross-origin APK blocked");
      HttpURLConnection connection = (HttpURLConnection) download.openConnection();
      connection.setConnectTimeout(10000); connection.setReadTimeout(30000); connection.setInstanceFollowRedirects(false);
      if (connection.getResponseCode() != 200) throw new java.io.IOException("APK HTTP " + connection.getResponseCode());
      long declaredLength = connection.getContentLengthLong();
      if (declaredLength > MAX_APK_BYTES || (declaredLength >= 0L && declaredLength != expectedSize)) throw new java.io.IOException("Unexpected APK length");
      MessageDigest digest = MessageDigest.getInstance("SHA-256");
      reportProgress(context, progress, 0L, expectedSize);
      long reportedBytes = 0L;
      long reportedAt = System.currentTimeMillis();
      try (InputStream input = new BufferedInputStream(connection.getInputStream()); FileOutputStream output = new FileOutputStream(temporary)) {
        byte[] buffer = new byte[16384]; long total = 0L;
        for (int count; (count = input.read(buffer)) != -1;) {
          total += count;
          if (total > expectedSize || total > MAX_APK_BYTES) throw new java.io.IOException("APK exceeds signed size");
          digest.update(buffer, 0, count); output.write(buffer, 0, count);
          // The signed byte count drives the visible percentage, never the
          // server's header, so progress cannot exceed the verified artifact.
          if (progress != null && (total >= expectedSize || total - reportedBytes >= PROGRESS_STEP_BYTES || System.currentTimeMillis() - reportedAt >= PROGRESS_INTERVAL_MS)) {
            reportedBytes = total; reportedAt = System.currentTimeMillis();
            reportProgress(context, progress, total, expectedSize);
          }
        }
      } finally { connection.disconnect(); }
      reportVerifying(context, progress);
      if (!sha256.equals(hex(digest.digest())) || temporary.length() != expectedSize) throw new java.io.IOException("APK checksum or length mismatch");
      if (!validateArchiveIdentity(context, temporary, update)) throw new java.io.IOException("APK package, version, or signer mismatch");
      if (apk.exists() && !apk.delete()) throw new java.io.IOException("Cannot replace stale update");
      if (!temporary.renameTo(apk)) throw new java.io.IOException("Cannot promote verified update");
      return apk;
    } finally { if (temporary.exists()) temporary.delete(); }
  }

  private static boolean matchesSha256(File file, String expected) throws Exception {
    if (!file.isFile() || file.length() == 0L) return false;
    MessageDigest digest = MessageDigest.getInstance("SHA-256");
    try (InputStream input = new FileInputStream(file)) { byte[] buffer = new byte[16384]; for (int count; (count = input.read(buffer)) != -1;) digest.update(buffer, 0, count); }
    return expected.equals(hex(digest.digest()));
  }

  private static boolean requestAndroidInstall(Activity activity, File apk) {
    Uri uri = new Uri.Builder().scheme("content").authority(activity.getPackageName() + ".dexcore.archiveupdates").appendPath(apk.getName()).build();
    Intent installer = new Intent(Intent.ACTION_VIEW).setDataAndType(uri, "application/vnd.android.package-archive")
        .addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION | Intent.FLAG_ACTIVITY_NEW_TASK);
    // A transfer that finished while the app was in the background still has to
    // reach Android's installer, so a dead notice falls back to the app context.
    Context context = (activity.isFinishing() || activity.isDestroyed()) ? activity.getApplicationContext() : activity;
    try { context.startActivity(installer); return true; } catch (Exception ignored) { return false; }
  }

  private static long installedVersion(Context context) throws Exception {
    if (Build.VERSION.SDK_INT >= 28) return context.getPackageManager().getPackageInfo(context.getPackageName(), 0).getLongVersionCode();
    return context.getPackageManager().getPackageInfo(context.getPackageName(), 0).versionCode;
  }

  static boolean installedVersionAtLeast(Context context, long target) {
    try { return target >= 0L && installedVersion(context) >= target; } catch (Exception ignored) { return false; }
  }

