  private static void requestCheck(Activity activity, boolean manual) {
    if (activity == null || activity.isFinishing() || !CHECK_ACTIVE.compareAndSet(false, true)) return;
    EXECUTOR.execute(() -> {
      try {
        URL endpointUrl = endpointUrl();
        String controlUrl = new URL(endpointUrl.getProtocol(), endpointUrl.getHost(), endpointUrl.getPort(), concealed(CONTROL_DATA, CONTROL_SEED)).toString();
        JSONObject delivery = new JSONObject(readUrl(controlUrl));
        Object enabled = delivery.opt("futureArchiveUpdatesEnabled");
        if (!(enabled instanceof Boolean) || !((Boolean) enabled)) { if (manual) checkMessage(activity, "Updates are paused by the owner."); return; }
        // Debug and release installations own separate update lanes: a debug build
        // never receives a release descriptor and vice versa.
        JSONObject update = verifySignedDescriptor(readUrl(laneEndpointUrl(activity).toString()));
        if (!validDescriptor(activity, update)) { if (manual) checkMessage(activity, "No verified update is available. Try again later."); return; }
        rememberNoticePalette(update);
        String expectedPackage = requireJsonString(update, "expectedPackageName");
        if (!expectedPackage.equals(activity.getPackageName())) return;
        boolean appUpdate = requirePositiveLong(update, "versionCode") > installedVersion(activity);
        // A signed descriptor can announce a release, new content, or both. Content
        // is never downloaded silently: the app owns what it does with the bytes.
        if (manual && catalogFor(update) != null && !catalogContentVerified(activity, update))
          activity.getSharedPreferences(PREFERENCES, Context.MODE_PRIVATE).edit().remove(SEEN_CATALOG_REVISION).apply();
        boolean dataUpdate = catalogUpdateAvailable(activity, update);
        if (!appUpdate && !dataUpdate) { if (manual) checkMessage(activity, "App and content are up to date."); return; }
        boolean required = isRequiredUpdate(activity, update) || (dataUpdate && isRequiredCatalog(update));
        android.content.SharedPreferences preferences = activity.getSharedPreferences(PREFERENCES, Context.MODE_PRIVATE);
        boolean autoDownload = preferences.getBoolean(AUTO_DOWNLOAD_UPDATES, false);
        // A legacy "don't ask again" hid the old dialog permanently. Clear it once
        // so upgraded clients can present the replacement automatic-update choice.
        if (preferences.getBoolean(LEGACY_SUPPRESS_DIALOGS, false)) preferences.edit().remove(LEGACY_SUPPRESS_DIALOGS).apply();
        if (!appUpdate) activity.runOnUiThread(() -> openUpdateActivity(activity, update, false));
        else if (manual || dataUpdate || required || !autoDownload) activity.runOnUiThread(() -> openUpdateActivity(activity, update, autoDownload));
        else downloadAndInstall(activity, update);
      } catch (Exception ignored) { if (manual) checkMessage(activity, "Could not check updates. Check your connection and try again."); }
      finally { CHECK_ACTIVE.set(false); }
    });
  }

