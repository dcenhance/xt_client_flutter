  // Progress reaches a visible Activity through its main thread; a background or
  // auto-download context has no listener and stays silent.
  private static void reportProgress(Context context, DownloadProgress progress, long downloaded, long totalBytes) {
    PROGRESS_DOWNLOADED = downloaded;
    PROGRESS_TOTAL = totalBytes;
    DownloadProgress listener = ACTIVE_PROGRESS.get();
    if (listener == null) listener = progress;
    if (listener == null) return;
    if (context instanceof Activity) {
      final Activity activity = (Activity) context;
      final DownloadProgress target = listener;
      MAIN.post(() -> target.onBytes(downloaded, totalBytes));
    } else listener.onBytes(downloaded, totalBytes);
  }
  private static void reportVerifying(Context context, DownloadProgress progress) {
    DownloadProgress listener = ACTIVE_PROGRESS.get();
    if (listener == null) listener = progress;
    if (listener == null) return;
    if (context instanceof Activity) {
      final Activity activity = (Activity) context;
      final DownloadProgress target = listener;
      MAIN.post(target::onVerifying);
    } else listener.onVerifying();
  }
  /** A notice attaches at any time; a transfer already in flight reports at once. */
  public static void attachProgress(Activity activity, DownloadProgress progress) {
    if (progress == null) return;
    ACTIVE_PROGRESS = new WeakReference<>(progress);
    if (activity == null) return;
    if (!DOWNLOAD_ACTIVE.get()) return;
    final long downloaded = PROGRESS_DOWNLOADED;
    final long total = PROGRESS_TOTAL;
    activity.runOnUiThread(() -> { if (!activity.isFinishing()) progress.onBytes(downloaded, total); });
  }
