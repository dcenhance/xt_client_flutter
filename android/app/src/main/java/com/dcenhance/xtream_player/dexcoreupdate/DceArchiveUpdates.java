  public static void downloadAndInstall(Activity activity, JSONObject update, DownloadProgress progress) {
    if (activity == null || activity.isFinishing() || !validDescriptor(activity, update)) { notifyDownloadFailure(activity, "Update verification failed. Try again."); return; }
    if (!DOWNLOAD_ACTIVE.compareAndSet(false, true)) {
      // A verified transfer is already running (for example after the notice was
      // closed and re-opened): re-attach to it instead of reporting a failure.
      if (progress != null) attachProgress(activity, progress);
      else notifyDownloadFailure(activity, "An update download is already running. Try again shortly.");
      return;
    }
    final String snapshot = update.toString();
    final DownloadProgress listener = progress;
    ACTIVE_PROGRESS = new WeakReference<>(progress);
    EXECUTOR.execute(() -> {
      try {
        File apk = downloadVerifiedApk(activity, new JSONObject(snapshot), listener);
        if (apk == null) throw new java.io.IOException("Verified download unavailable");
        activity.runOnUiThread(() -> {
          if (requestAndroidInstall(activity, apk)) notifyInstallerStarted(activity);
          else notifyDownloadFailure(activity, "Android could not open the installer. Try again.");
        });
      } catch (Exception ignored) { notifyDownloadFailure(activity, "Download or verification failed. Try again."); }
      finally { DOWNLOAD_ACTIVE.set(false); ACTIVE_PROGRESS = new WeakReference<>(null); }
    });
  }

  private static boolean validDescriptor(Context context, JSONObject update) {
    if (update == null) return false;
    try {
      URL endpoint = endpointUrl();
      URL download = new URL(requireJsonString(update, "downloadUrl"));
      long size = requirePositiveLong(update, "sizeBytes");
      String expectedPackage = requireJsonString(update, "expectedPackageName");
      return expectedPackage.length() > 0
          && expectedPackage.equals(context.getPackageName())
          && expectedPackage.equals(requireJsonString(update, "packageName"))
          && requirePositiveLong(update, "versionCode") > 0L
          && requireJsonString(update, "versionName").length() > 0
          && requireJsonString(update, "sha256").matches("[0-9a-fA-F]{64}")
          && size > 0L && size <= MAX_APK_BYTES
          && strictUpdatePolicy(requireJsonObject(update, "updatePolicy")) != null
          && strictSignerArray(update)
          && sameArchiveOrigin(endpoint, download)
          && download.getPath().startsWith(laneDirectoryPath(context));
    } catch (Exception invalid) { return false; }
  }

