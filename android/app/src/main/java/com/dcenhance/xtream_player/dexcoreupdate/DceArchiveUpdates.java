  private static void installForegroundChecks(Activity seed) {
    if (!LIFECYCLE_INSTALLED.compareAndSet(false, true)) return;
    seed.getApplication().registerActivityLifecycleCallbacks(new android.app.Application.ActivityLifecycleCallbacks() {
      @Override public void onActivityResumed(Activity activity) {
        if (activity instanceof DceArchiveUpdateActivity) return;
        FOREGROUND_ACTIVITY = new WeakReference<>(activity);
        RESUMED_ACTIVITIES.incrementAndGet();
        MAIN.removeCallbacks(FOREGROUND_POLL);
        requestCheck(activity);
        MAIN.postDelayed(FOREGROUND_POLL, FOREGROUND_POLL_INTERVAL_MS);
      }
      @Override public void onActivityPaused(Activity activity) {
        if (activity instanceof DceArchiveUpdateActivity) return;
        int remaining = RESUMED_ACTIVITIES.decrementAndGet();
        if (remaining <= 0) { RESUMED_ACTIVITIES.set(0); MAIN.removeCallbacks(FOREGROUND_POLL); }
      }
      @Override public void onActivityDestroyed(Activity activity) {
        Activity current = FOREGROUND_ACTIVITY.get();
        if (current == activity) FOREGROUND_ACTIVITY = new WeakReference<>(null);
      }
      @Override public void onActivityCreated(Activity activity, android.os.Bundle state) {}
      @Override public void onActivityStarted(Activity activity) {}
      @Override public void onActivityStopped(Activity activity) {}
      @Override public void onActivitySaveInstanceState(Activity activity, android.os.Bundle state) {}
    });
  }

